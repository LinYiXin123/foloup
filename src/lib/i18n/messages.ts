export type Locale = "zh-CN" | "en";
const englishMessages = Object.fromEntries(
  Object.entries(zhCNMessages).map(([english, chinese]) => [chinese, english]),
);
export function translate(
  message: string,
  locale: Locale,
  values?: Record<string, string | number>,
): string {
  let result =
    locale === "zh-CN" ? (zhCNMessages[message] ?? message) : (englishMessages[message] ?? message);
  if (locale === "en" && zhCNMessages[result]) {
    result = result.replaceAll("&apos;", "'").replaceAll("&quot;", '"').replaceAll("&amp;", "&");
  }
  for (const [key, value] of Object.entries(values ?? {})) {
    result = result.replaceAll(`{${key}}`, () => String(value));
  }
  return result;
}
